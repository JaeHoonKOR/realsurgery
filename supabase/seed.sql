## 쌍꺼풀 수술은 누가 받나요?

쌍꺼풀이 없거나 라인이 흐려 눈매를 또렷하게 하고 싶은 경우에 받는 수술입니다.[1] 눈꺼풀이 얇고 지방이 적으면 매몰법을, 피부가 두껍거나 처짐이 있으면 절개법을 주로 고려합니다.[2]

눈을 뜰 때 이마에 힘이 들어가거나 검은자가 눈꺼풀에 많이 가려진다면 눈매교정이 필요한지 함께 진찰받는 경우가 많습니다. 어떤 방법이 맞는지는 진찰 후 의료진이 판단합니다.[1]

## 쌍꺼풀 수술 비용은 얼마인가요?

쌍꺼풀 수술의 병원 공개 가격은 대략 50만~250만 원이며, 방법에 따라 차이가 큽니다.[3]

| 방법 | 공개 가격 범위 | 특징 |
| --- | --- | --- |
| 매몰법 | 50만~150만 원 | 절개 없이 실로 고정 |
| 절개법 | 100만~250만 원 | 피부·지방을 함께 정리 |

눈매교정이나 트임을 함께 하면 비용이 올라가므로, 견적서에 마취비·실밥 제거·재진료 비용이 포함되는지 확인하세요.[3]

## 쌍꺼풀 수술 회복은 며칠 걸리나요?

절개법은 보통 5~7일 뒤 실밥을 제거하고, 큰 붓기는 2~3주에 걸쳐 빠집니다.[2]

| 시점 | 일반적인 경과 |
| --- | --- |
| 수술 직후~3일 | 붓기와 멍이 가장 심한 시기 |
| 5~7일 | 실밥 제거(절개법) |
| 2~3주 | 큰 붓기가 빠지고 눈 화장 시작 |
| 수개월 | 라인이 자리 잡음 |

붓기 정도와 회복 속도는 사람마다 다르므로 병원 안내를 우선으로 따르세요.[2]

## 쌍꺼풀 수술 부작용과 주의할 점은 무엇인가요?

수술 뒤에는 좌우 비대칭, 라인 풀림, 흉터, 감염 같은 부작용이 생길 수 있습니다.[1]

- 라인 풀림: 실로만 고정하는 매몰법에서 더 자주 거론되며 재수술이 필요할 수 있습니다.
- 흉터·비대칭: 절개 위치와 피부 특성에 따라 정도가 다릅니다.
- 감염·염증: 처방받은 약과 세안 시작 시기 안내를 지켜야 합니다.

수술 전 상담에서 재수술 기준과 사후 관리 범위를 확인해 두는 것이 좋습니다.[2]

