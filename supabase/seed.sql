## 눈밑지방재배치는 누가 받나요?

눈밑 지방이 앞으로 밀려나와 불룩한 주머니가 생기고 그늘이 지는 경우에 고려하는 수술입니다.[1] 나이가 들면서 지방을 받치는 안와격막이 약해지면 지방이 튀어나오고, 코 옆 골격을 따라 그림자가 지거나 다크서클처럼 보이기도 합니다.[2]

하안검 성형 수술은 여분의 지방을 제거하거나 지방이 부족한 부위에 재배치하고, 늘어진 피부와 근육을 정리하는 방식으로 진행합니다.[1]

## 눈밑지방재배치 비용은 얼마인가요?

눈밑지방재배치의 참고 가격은 대략 100만~300만 원이며, 이 범위는 출처 검증 전 예시 데이터입니다. 미용 목적의 성형수술은 건강보험이 적용되지 않는 비급여 대상입니다.[3]

