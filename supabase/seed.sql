## 가슴 확대 수술은 누가 받나요?

선천적으로 가슴이 작거나 임신·체중 감소로 유방이 작아진 경우, 양쪽 크기 차이가 큰 경우에 받는 수술입니다.[1] 수술 전에는 유방의 크기·대칭·처짐 정도와 피부 두께를 진찰하고, 40세 이상이거나 유방암 가족력이 있으면 유방 촬영술로 유방 질환 여부를 확인합니다.[2]

## 가슴 확대 수술 비용은 얼마인가요?

가슴 확대 수술의 참고 가격은 보형물 종류에 따라 대략 600만~1,200만 원이며, 이 범위는 출처 검증 전 예시 데이터입니다. 미용 목적의 유방확대술은 건강보험이 적용되지 않는 비급여 대상입니다.[4]

