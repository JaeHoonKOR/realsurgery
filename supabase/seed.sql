## 눈매교정은 누가 받나요?

눈 뜨는 근육의 힘이 약해져 눈동자가 가려지거나 졸려 보이는 눈을 교정할 때 받는 수술입니다.[1] 정상적으로는 윗눈꺼풀이 검은자 윗부분을 1~2mm 정도 덮는데, 이보다 더 많이 덮이거나 눈을 뜰 때 이마에 힘이 들어간다면 안검하수를 의심해 볼 수 있습니다.[1]

안검하수 여부와 정도는 의료진 검사로 판단하며, 선천적·후천적 안검하수로 시야가 가려지거나 미용적인 문제가 있을 때 수술을 고려합니다.[1]

## 눈매교정 비용은 얼마인가요?

눈매교정의 참고 가격은 방식에 따라 대략 60만~350만 원이며, 이 범위는 출처 검증 전 예시 데이터입니다. 눈 기능 개선이 아닌 미용 목적의 눈꺼풀 수술은 건강보험이 적용되지 않는 비급여 대상입니다.[3]

