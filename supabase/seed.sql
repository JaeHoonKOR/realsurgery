## 가슴 확대 수술은 누가 받나요?

가슴 볼륨이 작거나 출산·체중 변화 뒤 볼륨이 줄어 고민인 경우에 고려하는 수술입니다.[2] 수술 전에는 유방 초음파 등으로 유방 상태를 먼저 확인합니다.[3]

## 가슴 확대 수술 비용은 얼마인가요?

가슴 확대 수술의 병원 공개 가격은 보형물 종류에 따라 대략 600만~1,200만 원입니다.[2]

| 견적 항목 | 확인할 점 |
| --- | --- |
| 수술비·마취비 | 전신 마취 비용 포함 여부 |
| 보형물 | 제품명과 표면·모양 |
| 사후 검진 | 검진 횟수와 기간 |

항목이 나뉘어 적힌 견적서를 받아 병원끼리 같은 기준으로 비교하세요.[2]

## 가슴 확대 수술 회복은 며칠 걸리나요?

일상 복귀까지 1~2주가 걸리고, 팔을 크게 쓰는 운동은 4~6주 뒤부터 권하는 경우가 많습니다.[3]

| 시점 | 일반적인 경과 |
| --- | --- |
| 1~2주 | 일상 복귀 |
| 4~6주 | 팔을 크게 쓰는 운동 시작 |
| 이후 정기 | 보형물 상태 검진 |

압박 속옷 착용 기간과 검진 일정은 병원 안내를 따르세요.[3]

## 가슴 확대 수술 부작용과 주의할 점은 무엇인가요?

보형물 주변이 단단해지는 구형구축, 보형물 파열, 비대칭, 감염, 감각 변화가 생길 수 있습니다.[2]

- 구형구축: 보형물 주변 막이 두꺼워지며 단단해지는 증상입니다.
- 파열: 증상 없이 생길 수 있어 정기 검진으로 확인합니다.

거친 표면 보형물은 드물게 역형성 대세포 림프종(BIA-ALCL)과의 연관성이 보고되어 식약처가 안전성 정보를 안내하고 있습니다.[1]

## 가슴 확대 수술과 비슷한 시술은 어떻게 다른가요?

보형물 가슴 확대는 볼륨 변화가 큰 편이고, 자가 지방 이식은 내 지방을 옮기는 대신 늘릴 수 있는 볼륨이 제한적입니다.[2]

