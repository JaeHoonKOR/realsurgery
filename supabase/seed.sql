## 레이저 토닝 부작용과 주의할 점은 무엇인가요?

레이저 시술 뒤에는 홍반, 부종, 딱지, 멍, 물집 같은 급성 반응이 나타날 수 있고, 착색이나 흉터, 피부색 변화가 생길 수도 있습니다.[2]

- 색소침착: 레이저 뒤에는 색소침착이 생길 수 있어, 피부가 회복된 뒤에도 자외선 차단에 각별히 신경 써야 합니다.
- 자가 관리: 세안은 부드럽게 하고, 사용할 제품이나 추가 관리법은 담당 피부과 전문의에게 확인합니다.

여성호르몬이 기미를 유발하거나 악화시킬 수 있어, 임신 중이거나 먹는 피임약을 복용 중이라면 상담할 때 알리세요.[1] 레이저 뒤 색소침착을 줄이려면 회복 뒤에도 자외선 차단을 이어가야 합니다.[3]

