| 쌍꺼풀 수술과 함께 | 묶음 견적으로 안내 |

쌍꺼풀 수술과 함께 받는다면 각 수술의 비용이 견적서에 나뉘어 적혀 있는지 확인하세요.[1]

## 눈매교정 회복은 며칠 걸리나요?

실밥은 5~7일 뒤 제거하고, 큰 붓기는 2~3주가량 이어집니다.[2]

눈 뜨는 높이가 안정되기까지는 수개월이 걸릴 수 있어, 초기 모양만으로 결과를 판단하지 않는 것이 좋습니다.[2]

## 눈매교정 부작용과 주의할 점은 무엇인가요?

눈매교정 뒤에는 과교정·저교정, 좌우 비대칭, 눈 감김 불편, 안구 건조감이 생길 수 있습니다.[1]

- 과교정·저교정: 눈 뜨는 높이가 계획보다 높거나 낮게 자리 잡을 수 있습니다.
- 안구 건조: 눈이 완전히 감기지 않으면 건조감이 생길 수 있어 인공눈물 등 관리 안내를 따릅니다.

재수술 기준과 비용 부담 범위를 수술 전에 확인하세요.[3]

