## 눈밑지방재배치는 누가 받나요?

눈밑 지방이 튀어나오고 그 아래가 꺼져 그늘이 지는 경우에 고려하는 수술입니다.[1] 피부 처짐이 심하다면 늘어진 피부를 함께 잘라내는 하안검 수술을 검토하기도 합니다.[2]

## 눈밑지방재배치 비용은 얼마인가요?

눈밑지방재배치의 병원 공개 가격은 대략 100만~300만 원입니다.[1]

| 진행 방식 | 가격 범위 안의 위치 |
| --- | --- |
| 결막 쪽 접근 단독 | 낮은 쪽 |
| 피부 절개 또는 지방 이식 추가 | 높은 쪽 |

수면 마취 비용과 재진료 비용이 견적에 포함되는지 함께 확인하세요.[1]

## 눈밑지방재배치 회복은 며칠 걸리나요?

멍과 붓기는 1~2주에 걸쳐 줄어들고, 출근은 보통 3~7일 뒤부터 가능하다고 안내합니다.[2]

| 시점 | 일반적인 경과 |
