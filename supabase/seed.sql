## 쌍꺼풀 수술 회복은 며칠 걸리나요?

보통 수술 후 3~4일째 봉합실을 제거하고, 1주일 정도면 정상생활로 돌아갈 수 있습니다.[1]

수술은 일반적으로 국소 마취로 하고 필요에 따라 진정제를 사용합니다.[1] 수술 시간은 방법에 따라 다르지만 대개 1시간 정도 걸립니다.[2]

| 시점 | 일반적인 경과 |
| --- | --- |
| 수술 후 2~3일 | 베개를 높이고 얼음찜질로 붓기를 가라앉히는 시기 |
| 3~4일 | 봉합실 제거, 하루 뒤부터 화장 가능 |
| 약 1주 | 정상생활 복귀 |
| 2~3개월 | 쌍꺼풀이 자리 잡음 |

절개법은 3~5일 뒤 실밥을 뽑고, 쌍꺼풀이 완전히 자연스러워지기까지 3~6개월이 걸린다는 설명도 있어 회복 기간은 방법과 사람에 따라 다릅니다.[2]

## 쌍꺼풀 수술 부작용과 주의할 점은 무엇인가요?

수술 뒤에는 혈종, 좌우 비대칭, 흉터가 생길 수 있고, 매몰법은 5% 이하의 환자에서 쌍꺼풀이 풀리기도 합니다.[1]

- 혈종: 수술 후 통증이 심해지고 눈이 눌리는 느낌과 붓기가 심해지면 바로 병원을 찾아야 합니다.
- 눈꺼풀 변형·안구건조: 눈꺼풀 겉말림·속말림·처짐, 안구건조증이 생길 수 있고, 드물게 복시나 실명 같은 심각한 합병증도 있습니다.
- 복용 중인 약: 아스피린·와파린 같은 항응고제·항혈소판제는 출혈과 혈종의 원인이 될 수 있어, 중단 여부를 의료진과 미리 상의해야 합니다.

평소 눈이 잘 마르고 뻑뻑하다면 수술 후 증상이 더 심해질 수 있으므로 상담할 때 알리세요.[1]

