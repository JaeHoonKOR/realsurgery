## 쌍꺼풀 수술은 누가 받나요?

쌍꺼풀이 없거나 한쪽에만 있어 눈꺼풀에 접히는 선을 만들고 싶을 때 받는 수술입니다.[1] 지방층이 두터워 눈이 더부룩하면 지방 제거를 함께 하기도 하고, 안검하수가 있으면 그 교정과 함께 쌍꺼풀을 만들 수 있습니다.[1]

사람마다 맞는 방법이 다르고 수술이 적합하지 않은 경우도 있어, 수술 전에 전문의와 충분히 상담해야 합니다.[1]

## 쌍꺼풀 수술 비용은 얼마인가요?

쌍꺼풀 수술의 참고 가격은 대략 50만~250만 원이며, 이 범위는 출처 검증 전 예시 데이터입니다. 미용 목적의 쌍꺼풀 수술은 건강보험이 적용되지 않는 비급여 대상입니다.[3]

