## 눈밑지방재배치 회복은 며칠 걸리나요?

피부를 절개한 경우 보통 4일 전후로 봉합실을 제거하고, 약 1주가 지나면 일상생활이 가능합니다.[1]

수술은 일반적으로 국소 마취로 하고 필요에 따라 진정제를 사용합니다.[1] 소요 시간은 피부를 절개하는 외과적 시술이 40~60분, 레이저 시술이 30~40분 정도입니다.[2]

