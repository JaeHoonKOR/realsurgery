## 코 성형은 누가 받나요?

코가 낮거나 변형이 있어 높이를 교정하거나 모양을 다듬고 싶은 경우에 받는 수술입니다.[2] 코막힘을 동반한 기능적인 변형이나 외상·이전 수술로 생긴 변형을 교정하기 위해 하기도 합니다.[1]

개개인의 해부학적 구조를 고려해, 필요한 방법을 성형외과 전문의의 판단에 따라 고르는 것이 좋습니다.[1]

