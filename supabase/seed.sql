## 레이저 토닝은 누가 받나요?

기미처럼 넓게 퍼진 갈색 색소를 옅게 하려는 경우에 많이 쓰이는 레이저 치료 방식입니다.[1] 기미는 볼·이마에 잘 생기는 갈색 또는 회갈색 반점으로, 자외선·여성호르몬·유전적 소인이 함께 작용해 생기거나 짙어집니다.[1]

레이저 치료의 종류는 진단명과 피부 상태에 따라 정하므로, 색소의 종류를 진찰로 먼저 구분합니다.[2]

## 레이저 토닝 비용은 얼마인가요?

