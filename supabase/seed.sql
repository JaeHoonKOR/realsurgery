## 가슴 확대 수술 회복은 며칠 걸리나요?

수술 후 일상생활은 가능하지만 과격한 운동은 2~3주까지 삼가고, 3주간 스포츠 브래지어를 착용합니다.[2]

수술은 수면 마취로 할 수도 있지만 보통 전신 마취로 합니다.[2] 예상 소요 시간은 2시간 정도이며, 수술 진행 상황에 따라 달라질 수 있습니다.[1]

| 시점 | 일반적인 경과 |
| --- | --- |
| 수술 당일~1일 | 당일 퇴원 또는 하루 입원 |
| 수술 직후 | 양팔 움직임 제한 |
| 3주 | 스포츠 브래지어 착용 |
| 1개월 | 격렬한 운동, 가슴 근육을 쓰는 운동은 피함 |

당일 수술로 가능하거나 하루 입원이 필요할 수 있고, 한 달간은 격렬한 운동, 특히 흉터를 벌어지게 할 수 있는 가슴 근육 운동을 피하는 것이 좋습니다.[1]

## 가슴 확대 수술 부작용과 주의할 점은 무엇인가요?

보형물 주변이 단단해지는 구형구축, 감염, 보형물의 위치 변화·파열, 비대칭 같은 합병증이 생길 수 있습니다.[1]

- 피막 구축: 유방 확대술 뒤 재수술의 가장 흔한 원인으로, 보통 1년 안에 나타나지만 한참 뒤에 생기기도 합니다.
- 정기 검사: 코히시브젤 보형물을 쓴 경우 수술 후 3년마다 MRI로 경과를 관찰해야 합니다.
- 유방암 검진: 매달 자가검진을 하고, 1~2년에 한 번은 유방암 전문 검진을 받는 것이 좋습니다.

거친 표면 보형물은 드물게 보형물 연관 역형성 대세포 림프종(BIA-ALCL)과 관련이 있어, 이식 후 1년이 지나면 증상이 없어도 1년에 1회 정기 진료를 받도록 권고됩니다.[3]

## 가슴 확대 수술과 비슷한 시술은 어떻게 다른가요?

가슴을 키우는 방법에는 보형물 삽입 외에 자가 지방 이식과 필러 제품을 이용하는 방법이 있습니다.[1] 보형물의 위치(유방조직 아래·가슴근 아래·이중평면)와 절개 위치는 가슴 상태에 따라 의료진과 상의해 정합니다.[2]

