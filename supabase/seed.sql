## 눈매교정은 누가 받나요?

눈을 뜰 때 검은자가 눈꺼풀에 많이 가려지거나 이마에 힘이 들어가는 경우에 고려합니다.[3] 안검하수 여부와 정도는 의료진 검사로 판단하며, 쌍꺼풀 수술과 함께 진행하는 경우가 많습니다.[1]

## 눈매교정 비용은 얼마인가요?

눈매교정의 병원 공개 가격은 방식에 따라 대략 60만~350만 원입니다.[1]

| 방식 | 가격 범위 안의 위치 |
| --- | --- |
