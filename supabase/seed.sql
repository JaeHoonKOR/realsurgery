| 약 4일 | 봉합실 제거(피부 절개 시) |
| 약 1주 | 일상생활 복귀 |
| 2~3주 이상 | 멍과 붓기가 남기도 함 |

눈 주위의 멍과 붓기는 2~3주 이상 이어지기도 합니다.[1] 수술 후 약 1주일은 코를 풀거나 눈을 비비지 말고, 잘 때 머리를 높여 붓기를 줄이세요.[2]

## 눈밑지방재배치 부작용과 주의할 점은 무엇인가요?

수술 뒤에는 일시적인 붓기와 멍이 생길 수 있고, 피부를 과도하게 제거하면 아래 눈꺼풀이 뒤집힐 수 있습니다.[2]

- 혈종: 수술 후 통증과 눈이 눌리는 느낌, 붓기가 심해지면 바로 병원을 찾아야 합니다.
- 눈꺼풀 변형·안구 건조: 눈꺼풀 겉말림·처짐, 안구건조증 같은 합병증이 생길 수 있습니다.
- 주름: 지방이 많거나 피부 탄력이 떨어진 경우 수술 뒤 주름이 생길 수 있습니다.

평소 눈이 잘 마르고 뻑뻑하다면 수술 후 증상이 심해질 수 있으므로 상담할 때 알리세요.[1]

