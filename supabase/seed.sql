## 사각턱 수술은 누가 받나요?

옆얼굴에서 턱뼈각이 두드러져 보이거나 이마 너비에 비해 턱 너비가 넓은 경우에 받는 수술입니다.[1] 원인이 아래턱뼈라면 수술을, 씹는 근육(교근)이 발달한 것이 원인이라면 보톡스 주사를 고려하므로 상담과 검사로 원인을 먼저 확인합니다.[2]

