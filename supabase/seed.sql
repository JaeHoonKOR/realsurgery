## 눈매교정 회복은 며칠 걸리나요?

수술 후 붓기는 1~2주 정도 지나면 나아지고, 6개월 정도 지나야 자연스러워집니다.[1]

협조가 가능한 성인은 국소 마취로 수술할 수 있고, 경우에 따라서는 전신 마취로 합니다.[1] 소요 시간은 2시간 정도로 추정되며 수술 진행 상황에 따라 달라질 수 있습니다.[1]

| 시점 | 일반적인 경과 |
| --- | --- |
| 1~2주 | 붓기가 나아짐 |
| 수술 후 한동안 | 잘 때 눈이 다 감기지 않을 수 있음 |
| 약 6개월 | 눈매가 자연스러워짐 |

눈이 다 감기지 않는 동안에는 각막에 상처가 생길 수 있어, 낮에는 인공눈물을, 밤에는 연고나 테이프를 써서 눈을 보호해야 합니다.[1]

## 눈매교정 부작용과 주의할 점은 무엇인가요?

환자 상태에 따라 안검하수가 재발해 재수술이 필요할 수 있고, 혈종·비대칭·안구 건조 같은 합병증이 생길 수 있습니다.[1]

- 아래를 볼 때의 차이: 처진 눈꺼풀을 끌어올리는 수술이라 아래를 볼 때 윗눈꺼풀이 덜 내려가 흰자위가 보일 수 있습니다.
- 혈종: 수술 후 통증과 눈이 눌리는 느낌, 붓기가 심해지면 바로 병원을 찾아야 합니다.
- 안구 건조: 평소 눈이 잘 마르는 편이라면 수술 후 증상이 더 심해질 수 있습니다.

수술 방법은 눈꺼풀이 처진 정도와 눈 뜨는 근육의 기능에 따라 정하므로, 진찰 결과와 함께 설명을 들으세요.[1]

